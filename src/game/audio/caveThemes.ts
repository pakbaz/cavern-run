/**
 * The theme for a cave. Indices past the end of the table wrap, so a longer
 * campaign keeps playing music rather than falling over.
 */
export function themeForCave(caveIndex: number): CaveTheme {
  const index = Number.isFinite(caveIndex) ? Math.max(0, Math.floor(caveIndex)) : 0;
  return THEMES[index % THEMES.length];
}
